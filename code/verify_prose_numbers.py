"""Recompute every quantitative claim the PROSE of the paper makes.

Companion to `verify_table.py` (which regenerates `tbl:approx-errors` and the
Hermite variant) and `verify_boro_cnst.py` (which regenerates
`tbl:boro-cnst-art`). Those scripts own the tables; this one owns the numbers
that appear only in sentences of `content/paper/moderation_extended.md`:
human wealth and the worst-shock probability in the calibration paragraph,
the moderation-ratio landmarks quoted around `fig:ModerationRatio`, the
accuracy RATIOS the prose derives from the two tables, the grid-design ratios
quoted around `fig:GridExtent`, the slackness of the near-constraint envelope,
the return-risk containment range and volatility threshold, and the portfolio
section's calibration, kink points, chord bows and link comparisons.

Each check logs one line of the form

    [OK ] <what the paper says> | recomputed <value>

so a reader can diff the paper against the solver without reading code. A
claim is marked MISS when the recomputation falls outside the tolerance
printed with it; nothing here is tuned to force agreement, and `main` exits
non-zero if any claim misses.

One family of prose number is deliberately NOT recomputed here because it
already has a generator that prints it: the production-grid, bound-clamped and
horizon-sweep comparisons of `code/explorations/horserace/run_horserace.py`.
The grid-extent sweep is likewise generated by
`code/explorations/grid-extent/run_grid_extent.py`, but nothing there prints
the RATIOS the prose quotes, so `check_grid_extent` re-derives them from that
sweep's stamped output.

Run from the repository root:

    uv run python code/verify_prose_numbers.py
"""

