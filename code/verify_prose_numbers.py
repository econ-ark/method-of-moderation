def check_portfolio_calibration(agent, sigma_star: float) -> None:
    """The stated parameter values and the Campbell-Viceira myopic share."""
    stated = {
        "CRRA": 5.0,
        "DiscFac": 0.9,
        "LivPrb": [0.98],
        "Rfree": [1.03],
        "PermGroFac": [1.01],
        "PermShkStd": [0.1],
        "TranShkStd": [0.1],
        "UnempPrb": 0.05,
        "IncUnemp": 0.3,
        "RiskyAvg": 1.08,
    }
    mismatched = {
        key: (init_portfolio[key], value)
        for key, value in stated.items()
        if np.any(np.asarray(init_portfolio[key]) != np.asarray(value))
    }
    _claim(
        "portfolio calibration",
        "CRRA 5, DiscFac 0.9, LivPrb 0.98, Rfree 1.03, PermGroFac 1.01, "
        "shock std 0.1 each, 5% unemployment paying 0.3, RiskyAvg 1.08",
        "all match init_portfolio" if not mismatched else f"mismatches {mismatched}",
        ok=not mismatched,
    )

    # HARK's `RiskyStd` could name either dispersion, so measure both. A fine
    # discretization pins the convention; the solver's own coarse RiskyDstn
    # then shows what the quadrature does to it.
    risky_avg = init_portfolio["RiskyAvg"]

    def _moments(dstn) -> tuple[float, float, float]:
        ret = np.asarray(np.atleast_2d(dstn.atoms)[0], dtype=float)
        pmv = np.asarray(dstn.pmv, dtype=float)
        mean_level = float(np.sum(pmv * ret))
        level_std = float(np.sqrt(np.sum(pmv * (ret - mean_level) ** 2)))
        mean_log = float(np.sum(pmv * np.log(ret)))
        log_std = float(np.sqrt(np.sum(pmv * (np.log(ret) - mean_log) ** 2)))
        return mean_level, log_std, level_std

    fine_mean, fine_log_std, fine_level_std = _moments(
        Lognormal(
            mean=risky_avg,
            sigma=init_portfolio["RiskyStd"],
        ).discretize(2000, method="equiprobable"),
    )
    _claim(
        "portfolio calibration",
        "risky asset with mean gross return 1.08 and log standard deviation 0.184",
        f"E[R] = {fine_mean:.4f}, log std = {fine_log_std:.4f} (level std "
        f"{fine_level_std:.4f}), so HARK's RiskyStd = "
        f"{init_portfolio['RiskyStd']:.6f} is the LOG std",
        ok=_close(fine_mean, 1.08, 0.005) and _close(fine_log_std, 0.184, 0.01),
    )
    solver_mean, solver_log_std, _ = _moments(agent.RiskyDstn)
    _note(
        f"the solver's own {np.asarray(agent.RiskyDstn.pmv).size}-node "
        f"equiprobable quadrature carries E[R] = {solver_mean:.4f} and log std "
        f"{solver_log_std:.4f}, compressed relative to the continuous 0.184",
    )

    crra = init_portfolio["CRRA"]
    std_log = init_portfolio["RiskyStd"]
    log_premium = float(np.log(risky_avg) - np.log(init_portfolio["Rfree"][0]))
    cv_share = log_premium / (crra * std_log**2)
    _claim(
        "portfolio",
        "the Campbell-Viceira log-linear share equityPrem/(CRRA*std^2) gives 0.28",
        f"equityPrem = log(E[R]) - log(Rfree) = {log_premium:.6f}, "
        f"/(CRRA * {std_log:.4f}^2) = {cv_share:.4f}",
        ok=_close(cv_share, 0.28, 0.02),
    )
    _claim(
        "portfolio",
        "against the 0.31 solved on the discretized return process",
        f"ShareLimit = {sigma_star:.4f}",
        ok=_close(sigma_star, 0.31, 0.02),
    )


def check_portfolio_bounds(sol_far, sigma_star: float) -> None:
    """The kink point and the crossing of the Bodie-Merton-Samuelson ceiling."""
    h_nrm = float(sol_far.hNrm)
    _note(f"portfolio hNrm = {h_nrm:.4f}")

    m_release = float(sol_far.ShareFuncAdj.mRelease)
    _claim(
        "portfolio",
        "the investor leaves the constraint at m = 7.25",
        f"mRelease (solved kink) = {m_release:.4f} (rtol 0.02 on 7.25)",
        ok=_close(m_release, 7.25, 0.02),
    )

    grid = np.geomspace(10.0, 200_000.0, 400_000)
    solved = sol_far.ShareFuncAdjDirect(grid)
    ceiling = sigma_star * (1.0 + h_nrm / grid)
    sign_change = np.flatnonzero(np.diff(np.sign(solved - ceiling)) != 0)
    crossing = float(grid[sign_change[0]]) if sign_change.size else float("nan")
    # The paper no longer quotes the crossing point (cut 2026-08-26); the claim
    # that survives is that the solved share's gap above sigma* closes more
    # slowly than the ceiling's h/m, which is exactly what a crossing shows.
    _claim(
        "portfolio",
        "the Bodie-Merton-Samuelson ceiling is crossed: the solved share's gap "
        "closes more slowly than h/m",
        f"solved share crosses the ceiling at m = {crossing:,.0f}",
        ok=np.isfinite(crossing),
    )


def check_portfolio_links(sol_far, ref_sol, sigma_star: float) -> None:
    """Chord bows of the candidate transforms, and the five-node link scores."""
    grid = np.geomspace(10.0, 1000.0, 300)
    share = sol_far.ShareFuncAdjDirect(grid)
    omega = np.clip((share - sigma_star) / (1.0 - sigma_star), 1e-12, 1 - 1e-12)
    bows = {}
    for label, values in (
        ("share", share),
        ("logit", np.log(omega) - np.log1p(-omega)),
        ("log omega", np.log(omega)),
    ):
        scaled = (values - values.min()) / (values.max() - values.min())
        chord = np.linspace(scaled[0], scaled[-1], scaled.size)
        bows[label] = 100.0 * float(np.abs(scaled - chord).max())
    _claim(
        "portfolio",
        "over m in [10, 1e3] the untransformed share departs from its chord by "
        "39 percent of the plotted range",
        f"share bow = {bows['share']:.1f}% (rtol 0.05 on 39)",
        ok=_close(bows["share"], 39.0, 0.05),
    )
    _claim(
        "portfolio",
        "and the logit by 14 percent",
        f"logit bow = {bows['logit']:.1f}% (rtol 0.08 on 14)",
        ok=_close(bows["logit"], 14.0, 0.08),
    )
    _claim(
        "portfolio",
        "log(shareModRte) departs by 1.4 percent",
        f"log-omega bow = {bows['log omega']:.2f}% (rtol 0.10 on 1.4)",
        ok=_close(bows["log omega"], 1.4, 0.10),
    )

    probe = np.geomspace(25.0, 100.0, 400)
    truth = ref_sol.ShareFuncAdj(probe)
    nodes = np.geomspace(25.0, 100.0, 5)
    s_nodes = ref_sol.ShareFuncAdj(nodes)
    om_nodes = np.clip(
        (s_nodes - sigma_star) / (1.0 - sigma_star),
        1e-12,
        1 - 1e-12,
    )
    baseline = float(
        np.abs(LinearInterp(nodes, s_nodes, lower_extrap=True)(probe) - truth).max(),
    )
    links = {
        "log": (np.log, np.exp),
        "logit": (
            lambda o: np.log(o) - np.log1p(-o),
            lambda z: 1.0 / (1.0 + np.exp(-z)),
        ),
        "cloglog": (
            lambda o: np.log(-np.log1p(-o)),
            lambda z: -np.expm1(-np.exp(z)),
        ),
    }
    ratios = {}
    for name, (fwd, inv) in links.items():
        interpolated = LinearInterp(
            np.log(nodes),
            fwd(om_nodes),
            lower_extrap=True,
        )(np.log(probe))
        approx = sigma_star + (1.0 - sigma_star) * inv(interpolated)
        ratios[name] = baseline / float(np.abs(approx - truth).max())
    _note(f"five-node baseline (interpolate the share itself) max err {baseline:.3e}")
    _claim(
        "portfolio",
        "with five nodes the logarithm is roughly a hundred times more accurate "
        "than interpolating the share itself",
        f"log ratio = {ratios['log']:.1f}x (rtol 0.20 on 100)",
        ok=_close(ratios["log"], 100.0, 0.20),
    )
    _claim(
        "portfolio",
        "the complementary log-log eight times",
        f"cloglog ratio = {ratios['cloglog']:.1f}x (rtol 0.20 on 8)",
        ok=_close(ratios["cloglog"], 8.0, 0.20),
    )
    _claim(
        "portfolio",
        "and the logit four times",
        f"logit ratio = {ratios['logit']:.1f}x (rtol 0.20 on 4)",
        ok=_close(ratios["logit"], 4.0, 0.20),
    )


def check_portfolio_accuracy(ref_sol, sigma_star: float) -> None:
    """Node-count sweeps clear of the kink and on a grid spanning it."""
    probe = np.geomspace(25.0, 100.0, 400)
    truth = ref_sol.ShareFuncAdj(probe)
    clear_ratios = {}
    for n in (4, 5, 7):
        nodes = np.geomspace(25.0, 100.0, n)
        s_nodes = ref_sol.ShareFuncAdj(nodes)
        moderated = ModeratedShareFunc(nodes, s_nodes, sigma_star)
        linear = np.abs(
            LinearInterp(nodes, s_nodes, lower_extrap=True)(probe) - truth,
        )
        clear_ratios[n] = float(linear.max() / np.abs(moderated(probe) - truth).max())
    _note(
        "clear-of-kink ratios by node count: "
        + ", ".join(f"n={n}: {r:.1f}x" for n, r in clear_ratios.items()),
    )
    lo, hi = min(clear_ratios.values()), max(clear_ratios.values())
    _claim(
        "portfolio",
        "clear of the kink, moderation is between seventy and a hundred and "
        "fifty times more accurate on four to seven nodes",
        f"ratio range = [{lo:.1f}x, {hi:.1f}x] (bounds compared after rounding "
        "to the nearest ten)",
        ok=round(lo / 10.0) * 10 >= 70.0 and round(hi / 10.0) * 10 <= 150.0,
    )
    _claim(
        "portfolio",
        "with the advantage growing as the grid coarsens",
        "ratios by node count (4, 5, 7) = "
        + ", ".join(f"{clear_ratios[n]:.1f}" for n in (4, 5, 7)),
        ok=clear_ratios[4] > clear_ratios[5] > clear_ratios[7],
    )

    probe2 = np.geomspace(1.0, 100.0, 2000)
    truth2 = ref_sol.ShareFuncAdj(probe2)
    tail_ratios, mid_ratios = {}, {}
    for n in (8, 12, 20):
        nodes = np.geomspace(1.0, 100.0, n)
        s_nodes = ref_sol.ShareFuncAdj(nodes)
        moderated = ModeratedShareFunc(nodes, s_nodes, sigma_star)
        linear = np.abs(
            LinearInterp(nodes, s_nodes, lower_extrap=True)(probe2) - truth2,
        )
        mod_err = np.abs(moderated(probe2) - truth2)
        tail = probe2 >= moderated.mBridge
        mid = (probe2 > moderated.mRelease) & (probe2 < moderated.mBridge)
        tail_ratios[n] = float(linear[tail].max() / mod_err[tail].max())
        mid_ratios[n] = float(linear[mid].max() / mod_err[mid].max())
    _note(
        "spanning-grid tail ratios: "
        + ", ".join(f"n={n}: {r:.1f}x" for n, r in tail_ratios.items()),
    )
    _note(
        "spanning-grid transition ratios: "
        + ", ".join(f"n={n}: {r:.2f}x" for n, r in mid_ratios.items()),
    )
    _claim(
        "portfolio",
        "on a grid spanning the constrained region our tail advantage runs from "
        "twelve to over a hundred times",
        f"tail ratio range = [{min(tail_ratios.values()):.1f}x, "
        f"{max(tail_ratios.values()):.1f}x]",
        ok=round(min(tail_ratios.values())) >= 12 and max(tail_ratios.values()) > 100.0,
    )
    _claim(
        "portfolio",
        "across the transition it is about twice",
        f"transition ratio range = [{min(mid_ratios.values()):.2f}x, "
        f"{max(mid_ratios.values()):.2f}x]",
        ok=1.5 <= float(np.median(list(mid_ratios.values()))) <= 2.5,
    )


def check_portfolio() -> None:
    """Solve the portfolio problem once and run every portfolio-section check."""
    logger.info("== Portfolio choice ==")
    agent = PortfolioMoMConsumerType(**(init_portfolio | PORTFOLIO_GRID))
    agent.solve()
    sigma_star = float(agent.solution[0].ShareLimit)

    far = PortfolioMoMConsumerType(**(init_portfolio | PORTFOLIO_FAR))
    far.solve()
    sol_far = far.solution[0]

    reference = PortfolioConsumerType(**(init_portfolio | PORTFOLIO_REF))
    reference.solve()
    ref_sol = reference.solution[0]

    check_portfolio_calibration(agent, sigma_star)
    check_portfolio_bounds(sol_far, sigma_star)
    check_portfolio_links(sol_far, ref_sol, sigma_star)
    check_portfolio_accuracy(ref_sol, sigma_star)


def main() -> int:
    # `force=True` is needed because HARK's import path installs root logging
    # handlers that would otherwise suppress this script's INFO output.
    logging.basicConfig(level=logging.INFO, format="%(message)s", force=True)
    started = time.perf_counter()

    check_calibration()
    check_moderation_ratio()
    check_accuracy_ratios()
    check_grid_extent()
    check_envelope_slack()
    check_return_risk()
    check_portfolio()

    misses = [row for row in _RESULTS if not row[3]]
    logger.info("")
    logger.info(
        "Checked %d prose claims in %.1f s: %d match, %d miss.",
        len(_RESULTS),
        time.perf_counter() - started,
        len(_RESULTS) - len(misses),
        len(misses),
    )
    for section, wording, recomputed, _ in misses:
        logger.error("MISS [%s] %s -> %s", section, wording, recomputed)
    return 1 if misses else 0


if __name__ == "__main__":
    sys.exit(main())
