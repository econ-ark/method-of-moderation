_RESULTS: list[tuple[str, str, str, bool]] = []


def _claim(section: str, wording: str, recomputed: str, *, ok: bool) -> None:
    """Record and log one paper claim against its recomputation."""
    _RESULTS.append((section, wording, recomputed, ok))
    logger.info(
        "  [%s] paper: %s | recomputed: %s",
        "OK " if ok else "MISS",
        wording,
        recomputed,
    )


def _note(text: str) -> None:
    """Log a supporting quantity the paper does not itself quote."""
    logger.info("       (%s)", text)


def _close(value: float, stated: float, rtol: float) -> bool:
    return bool(abs(value - stated) <= rtol * abs(stated))


