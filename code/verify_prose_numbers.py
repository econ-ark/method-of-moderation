_GRID_EXTENT_DIR = _THIS_DIR / "explorations" / "grid-extent"


def _load_grid_extent() -> dict[str, dict] | None:
    """Variants from the grid-extent sweep, refusing a stale JSON.

    `run_grid_extent.py` is the generator of record; this only re-derives the
    RATIOS the paper quotes from its output, since the sweep itself is too
    slow to repeat here.
    """
    payload = _GRID_EXTENT_DIR / "grid_extent.json"
    if not payload.exists():
        return None
    spec = importlib.util.spec_from_file_location(
        "run_grid_extent",
        _GRID_EXTENT_DIR / "run_grid_extent.py",
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    result = json.loads(payload.read_text())
    expected = {k: repr(v) for k, v in sorted(module.PARAMS.items())}
    if result.get("params") != expected:
        msg = (
            "grid_extent.json was produced by different parameters than the "
            "current run_grid_extent.py; rerun that sweep before trusting "
            "these ratios."
        )
        raise RuntimeError(msg)
    return {variant["label"]: variant for variant in result["variants"]}


def check_grid_extent() -> None:
    """The density-versus-extent ratios quoted around fig:GridExtent."""
    logger.info("== Grid design (fig:GridExtent paragraph) ==")
    variants = _load_grid_extent()
    if variants is None:
        logger.warning(
            "  grid_extent.json is absent; run "
            "code/explorations/grid-extent/run_grid_extent.py to cover the "
            "grid-extent prose claims.",
        )
        return

    def err(label: str) -> float:
        return float(variants[label]["max_abs_err"])

    base = err("paper-linear-5pt")
    density = err("count30-same-extent") / base
    _claim(
        "grid design",
        "raising the point count from five to thirty at the five-point grid's "
        "own extent does not improve the beyond-grid error at all (it rises "
        "slightly)",
        f"beyond-grid error {base:.3e} -> {err('count30-same-extent'):.3e}, "
        f"a factor of {density:.2f}",
        ok=density > 1.0,
    )
    two_h = [base / err(f"nest{n}-a2h") for n in (2, 3)]
    _claim(
        "grid design",
        "raising the grid top to twice human wealth improves it by roughly an "
        "order of magnitude",
        "improvement over the five-point extent = "
        + ", ".join(f"nest{n}: {r:.1f}x" for n, r in zip((2, 3), two_h, strict=True)),
        ok=all(3.0 <= r <= 30.0 for r in two_h),
    )
    further = [err(f"nest{n}-a2h") / err(f"nest{n}-a4h") for n in (2, 3)]
    _claim(
        "grid design",
        "with a further factor of two by four times human wealth",
        "2h -> 4h improvement = "
        + ", ".join(f"nest{n}: {r:.2f}x" for n, r in zip((2, 3), further, strict=True)),
        ok=all(_close(r, 2.0, 0.25) for r in further),
    )
    # "A third more accurate" reads as a third less error, so score the
    # fractional reduction below rather than the ratio of the two errors.
    reductions = [1.0 - err(f"nest2-a{r}") / err(f"nest3-a{r}") for r in ("2h", "4h")]
    _claim(
        "grid design",
        "past human wealth, double-exponential spacing is about a third more "
        "accurate beyond the grid than triple",
        "error reduction of nest2 against nest3 = "
        + ", ".join(
            f"a{r}: {100 * x:.0f}%"
            for r, x in zip(("2h", "4h"), reductions, strict=True)
        ),
        ok=all(0.25 <= x <= 0.42 for x in reductions),
    )
    coincide = [
        abs(1.0 - err(f"nest2-a{r}") / err(f"nest3-a{r}")) for r in ("0.5h", "1h")
    ]
    _claim(
        "grid design",
        "the two spacings coincide at small extents",
        "relative gap at a=0.5h, 1h = "
        + ", ".join(f"{100 * x:.1f}%" for x in coincide),
        ok=all(x < 0.02 for x in coincide),
    )


