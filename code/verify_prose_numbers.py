def check_calibration() -> None:
    """Human wealth, the worst-shock probability, and the natural constraint."""
    logger.info("== Calibration paragraph (Benchmark section) ==")
    rfree = PARAMS["Rfree"][0]

    finite = IndShockMoMConsumerType(**(PARAMS | SPARSE_GRID))
    finite.solve()
    sol = finite.solution[0]

    _claim(
        "calibration",
        "h_{T-1} = 1/Rfree ~ 0.98",
        f"hNrm(T-1) = {sol.hNrm:.6f}, 1/Rfree = {1.0 / rfree:.6f}",
        ok=_close(sol.hNrm, 1.0 / rfree, 1e-10) and round(sol.hNrm, 2) == 0.98,
    )

    infinite = IndShockMoMConsumerType(**(PARAMS | SPARSE_GRID | {"cycles": 0}))
    infinite.solve()
    h_inf = infinite.solution[0].hNrm
    _claim(
        "calibration",
        "infinite-horizon human wealth is 50",
        f"hNrm(inf) = {h_inf:.6f}, 1/(Rfree-1) = {1.0 / (rfree - 1.0):.6f} "
        "(rtol 1e-4: the solved value carries the solver's own convergence "
        "tolerance)",
        ok=_close(h_inf, 1.0 / (rfree - 1.0), 1e-4),
    )

    # The worst transitory draw and its probability, straight off the solver's
    # own discretized income process (seven equiprobable positive points).
    dstn = finite.IncShkDstn[0]
    tran = np.asarray(dstn.atoms[1], dtype=float)
    pmv = np.asarray(dstn.pmv, dtype=float)
    tran_min = float(tran.min())
    worst_prob = float(pmv[tran == tran_min].sum())
    _claim(
        "calibration",
        "WorstProb = 1/7 (worst draw is one point of a seven-point grid)",
        f"WorstProb = {worst_prob:.6f}, 1/7 = {1 / 7:.6f}, grid size = {tran.size}",
        ok=_close(worst_prob, 1 / 7, 1e-10),
    )
    _claim(
        "calibration",
        "no zero-income atom: worst draw is strictly positive",
        f"tranShkMin = {tran_min:.6e}",
        ok=tran_min > 0.0,
    )
    _claim(
        "calibration",
        "the natural borrowing constraint is negative",
        f"mNrmMin = {sol.mNrmMin:.6f}, -tranShkMin/Rfree = {-tran_min / rfree:.6f}",
        ok=sol.mNrmMin < 0.0,
    )
    _note(f"MPCmin = {sol.MPCmin:.6f}, MPCmax = {sol.MPCmax:.6f}")

    # Table 1 caption: the five endogenous gridpoints. The MoM x_list carries a
    # duplicated mNrmMin entry at the front and an augmentation point at the
    # back; the EGM gridpoints proper are the five in between.
    grid_pts = np.asarray(sol.cFunc.x_list)[1:6]
    quoted = np.array([-0.13, 2.34, 4.47, 6.57, 8.64])
    _claim(
        "calibration",
        "Table 1 gridpoints m_0..m_4 = -0.13, 2.34, 4.47, 6.57, 8.64",
        "solved gridpoints = " + ", ".join(f"{m:.3f}" for m in grid_pts),
        ok=grid_pts.size == 5 and bool(np.all(np.abs(grid_pts - quoted) < 0.006)),
    )


