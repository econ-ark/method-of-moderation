def _table_errors(
    *,
    cubic: bool = False,
    perm_shk: bool = False,
) -> tuple[list[float], list[float]]:
    """EGM and MoM interval errors, exactly as `verify_table` computes them."""
    params = PARAMS | {"CubicBool": True} if cubic else PARAMS
    if perm_shk:
        params = params | {"PermShkStd": [0.1], "PermShkCount": 5}
    truth = _solve(IndShockEGMConsumerType, params, DENSE_GRID)
    egm = _solve(IndShockEGMConsumerType, params, SPARSE_GRID)
    mom = _solve(IndShockMoMConsumerType, params, SPARSE_GRID)
    grid_pts = np.array(egm.cFunc.x_list)[1:]
    return (
        _interval_max_errors(truth.cFunc, egm.cFunc, grid_pts, M_BAR, N_EVAL),
        _interval_max_errors(truth.cFunc, mom.cFunc, grid_pts, M_BAR, N_EVAL),
    )


def check_accuracy_ratios() -> None:
    """The EGM/MoM ratios the prose derives from tbl:approx-errors and its twin."""
    logger.info("== Accuracy ratios quoted in prose (Table 1 and the cubic twin) ==")
    egm_lin, mom_lin = _table_errors()
    egm_cub, mom_cub = _table_errors(cubic=True)
    ratio_lin = [e / m for e, m in zip(egm_lin, mom_lin, strict=True)]
    ratio_cub = [e / m for e, m in zip(egm_cub, mom_cub, strict=True)]
    _note("linear EGM  = " + ", ".join(f"{e:.3e}" for e in egm_lin))
    _note("linear MoM  = " + ", ".join(f"{e:.3e}" for e in mom_lin))
    _note("linear ratio= " + ", ".join(f"{r:.2f}" for r in ratio_lin))
    _note("cubic  EGM  = " + ", ".join(f"{e:.3e}" for e in egm_cub))
    _note("cubic  MoM  = " + ", ".join(f"{e:.3e}" for e in mom_cub))
    _note("cubic  ratio= " + ", ".join(f"{r:.2f}" for r in ratio_cub))

    _claim(
        "abstract / Table 1",
        "MoM more accurate than EGM in every interval",
        f"min ratio over the five columns = {min(ratio_lin):.2f}",
        ok=min(ratio_lin) > 1.0,
    )
    _claim(
        "Table 1 prose",
        "in the first interval we manage about three and a half times",
        f"ratio[m0,m1] = {ratio_lin[0]:.2f} (rtol 0.10 on 3.5)",
        ok=_close(ratio_lin[0], 3.5, 0.10),
    )
    _claim(
        "Table 1 prose",
        "more than an order of magnitude in the remaining interior intervals",
        "interior ratios = " + ", ".join(f"{r:.2f}" for r in ratio_lin[1:4]),
        ok=min(ratio_lin[1:4]) > 10.0,
    )
    _claim(
        "abstract / Table 1 prose",
        "roughly forty-six times more accurate in the extrapolation region",
        f"ratio[m4,mbar] = {ratio_lin[4]:.2f} (rtol 0.05 on 46)",
        ok=_close(ratio_lin[4], 46.0, 0.05),
    )

    fall_first = mom_lin[0] / mom_cub[0]
    fall_rest = [mom_lin[j] / mom_cub[j] for j in (1, 2, 3)]
    _claim(
        "cubic prose",
        "moderation's interior error falls by a factor of five in the first interval",
        f"MoM linear/cubic in [m0,m1] = {fall_first:.2f} (rtol 0.15 on 5)",
        ok=_close(fall_first, 5.0, 0.15),
    )
    _claim(
        "cubic prose",
        "and by roughly two to three orders of magnitude in the rest",
        "MoM linear/cubic in the other interior intervals = "
        + ", ".join(f"{f:.1f}" for f in fall_rest),
        ok=min(fall_rest) >= 10.0 and max(fall_rest) <= 3000.0,
    )
    _claim(
        "cubic prose",
        "beyond the first interval the advantage grows from eleven or "
        "seventeen times under linear",
        "linear interior ratios = " + ", ".join(f"{r:.1f}" for r in ratio_lin[1:4]),
        ok=round(min(ratio_lin[1:4])) == 11 and round(max(ratio_lin[1:4])) == 17,
    )
    _claim(
        "cubic prose",
        "to between thirty-eight and fifty-six times under cubic",
        "cubic interior ratios = " + ", ".join(f"{r:.1f}" for r in ratio_cub[1:4]),
        ok=min(ratio_cub[1:4]) >= 38.0 and max(ratio_cub[1:4]) <= 56.0,
    )
    # The paper's stated endpoints are recoverable only from the ROUNDED table
    # entries; the raw solver ratios sit inside them, so "between" holds but
    # neither endpoint is attained.
    rounded = [
        round(float(f"{e:.2g}") / float(f"{m:.2g}"), 1)
        for e, m in zip(egm_cub[1:4], mom_cub[1:4], strict=True)
    ]
    _note(
        "recomputed from the two-significant-digit table entries the same "
        "ratios are " + ", ".join(f"{r:.1f}" for r in rounded),
    )
    _claim(
        "cubic prose",
        "in the first interval it slips from about three and a half times to three",
        f"linear {ratio_lin[0]:.2f} -> cubic {ratio_cub[0]:.2f} (rtol 0.10 on 3.0)",
        ok=_close(ratio_cub[0], 3.0, 0.10),
    )
    _claim(
        "cubic prose",
        "beyond the top gridpoint moderation's error barely moves, 3.0(-3) to 2.4(-3)",
        f"MoM extrapolation error {mom_lin[4]:.2e} (linear) -> "
        f"{mom_cub[4]:.2e} (cubic)",
        ok=_close(mom_lin[4], 3.0e-3, 0.06) and _close(mom_cub[4], 2.4e-3, 0.06),
    )
    _claim(
        "cubic prose",
        "the ratio between the methods is forty-six in one table and forty-five "
        "in the other",
        f"extrapolation ratio linear {ratio_lin[4]:.2f}, cubic {ratio_cub[4]:.2f}",
        ok=_close(ratio_lin[4], 46.0, 0.05) and _close(ratio_cub[4], 45.0, 0.05),
    )

    # The permanent-shock footnote: verify_table carries the switch that prints
    # the levels, but the "less than a factor of two" comparison against the
    # baseline table appears only in the footnote's prose.
    egm_ps, mom_ps = _table_errors(perm_shk=True)
    moves = [
        max(a / b, b / a)
        for a, b in zip(egm_ps + mom_ps, egm_lin + mom_lin, strict=True)
    ]
    _note("permshk EGM = " + ", ".join(f"{e:.1e}" for e in egm_ps))
    _note("permshk MoM = " + ", ".join(f"{e:.1e}" for e in mom_ps))
    _claim(
        "permanent-shock footnote",
        "restoring permanent shocks moves every entry of Table 1 by less than a "
        "factor of two",
        f"largest entrywise move = {max(moves):.2f}x",
        ok=max(moves) < 2.0,
    )
    _claim(
        "permanent-shock footnote",
        "and leaves the ordering intact",
        "MoM <= EGM in every column: "
        f"{all(m <= e for m, e in zip(mom_ps, egm_ps, strict=True))}",
        ok=all(m <= e for m, e in zip(mom_ps, egm_ps, strict=True)),
    )


