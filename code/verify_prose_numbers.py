def check_return_risk() -> None:
    """Bracket containment under return risk, and the volatility threshold."""
    logger.info("== Return risk (Stochastic Rate of Return section) ==")
    # In this module RiskyStd is a LEVEL standard deviation, which is why the
    # paper words the calibration as "a level standard deviation of 0.08".
    risky_std = 0.08
    params = PARAMS | {"RiskyAvg": PARAMS["Rfree"][0], "RiskyStd": risky_std}
    agent = RiskyAssetMoMConsumerType(**params)
    agent.solve()
    sol = agent.solution[0]

    n_probe = 2000
    probe = np.linspace(sol.mNrmMin + 0.01, 10.0, n_probe)
    c_real = sol.cFunc(probe)
    c_opt = sol.OptimistStochastic.cFunc(probe)
    c_pes = sol.PessimistStochastic.cFunc(probe)
    omega = (c_real - c_pes) / (c_opt - c_pes)
    _claim(
        "return risk",
        "the realist's rule stays strictly inside the bracket at every one of "
        "two thousand probe points between the constraint and m = 10",
        f"{probe.size} probes on [{probe[0]:.4f}, {probe[-1]:.1f}], strictly "
        f"inside: {bool(np.all((omega > 0) & (omega < 1)))}",
        ok=probe.size == n_probe and bool(np.all((omega > 0) & (omega < 1))),
    )
    _claim(
        "return risk",
        "the moderation ratio ranges over [0.005, 0.770]",
        f"omega range = [{omega.min():.4f}, {omega.max():.4f}] "
        "(rtol 0.05 on each endpoint)",
        ok=_close(float(omega.min()), 0.005, 0.05)
        and _close(float(omega.max()), 0.770, 0.05),
    )

    crra = PARAMS["CRRA"]
    inc_dstn = agent.IncShkDstn[0]

    def moments(std: float) -> tuple[float, float]:
        joint = create_joint_distribution(inc_dstn, params["RiskyAvg"], std)
        ret = np.asarray(joint.atoms[2], dtype=float)
        pmv = np.asarray(joint.pmv, dtype=float)
        return (
            float(np.sum(pmv * ret ** (1.0 - crra))),
            float(np.sum(pmv * ret ** (-crra))),
        )

    num_08, den_08 = moments(risky_std)
    _claim(
        "return risk",
        "the calibration satisfies E[R^-rho] < E[R^(1-rho)] at RiskyStd = 0.08",
        f"E[R^(1-rho)] = {num_08:.6f}, E[R^-rho] = {den_08:.6f}",
        ok=den_08 < num_08,
    )

    # Locate the volatility at which the two moments cross.
    grid = np.arange(0.02, 0.2005, 0.0005)
    holds = np.array([moments(float(s))[1] < moments(float(s))[0] for s in grid])
    flips = np.flatnonzero(np.diff(holds.astype(int)) != 0)
    threshold = float(grid[flips[0] + 1]) if flips.size else float("nan")
    _claim(
        "return risk footnote",
        "E[R^-rho] overtakes E[R^(1-rho)] near a volatility of 0.10",
        f"crossing at RiskyStd = {threshold:.4f} (rtol 0.10 on 0.10)",
        ok=_close(threshold, 0.10, 0.10),
    )

    joint_08 = create_joint_distribution(inc_dstn, params["RiskyAvg"], risky_std)
    shadow = calc_return_factor_human_wealth(joint_08, crra)
    _note(
        f"shadow riskless return Rtilde = E[R^(1-rho)]/E[R^-rho] = "
        f"{shadow:.6f} against Rfree = {PARAMS['Rfree'][0]}; hNrmOpt = "
        f"{1.0 / (shadow - 1.0):.4f}",
    )


