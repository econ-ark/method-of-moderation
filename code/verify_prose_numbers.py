def check_envelope_slack() -> None:
    """Is the tighter bound MPCmax*mNrmEx slack over the tabulated range?"""
    logger.info("== Near-constraint envelope (A Tighter Upper Bound) ==")
    agent = IndShockMoMConsumerType(**(PARAMS | SPARSE_GRID))
    agent.solve()
    sol = agent.solution[0]
    egm = IndShockEGMConsumerType(**(PARAMS | SPARSE_GRID))
    egm.solve()
    # The table's first tabulated gridpoint: verify_table drops index 0 (the
    # natural borrowing constraint) and starts the intervals at index 1.
    m0 = float(np.array(egm.solution[0].cFunc.x_list)[1])

    def bound(m: np.ndarray) -> np.ndarray:
        """eq:cFuncLowerEnvelope's tighter branch, MPCmax * (m - mNrmMin)."""
        return sol.MPCmax * (m - sol.mNrmMin)

    probe = np.linspace(m0 + 1e-8, M_BAR, 400_001)
    gap = bound(probe) - sol.cFunc(probe)
    _claim(
        "tighter upper bound",
        "the envelope is slack over the tabulated range under the natural constraint",
        f"min(bound - cMoM) on [m0={m0:.4f}, {M_BAR:.0f}] = {gap.min():.3e}",
        ok=bool(gap.min() > 0.0),
    )

    fine = np.linspace(sol.mNrmMin, m0 + 0.01, 2_000_001)
    binding = fine[(bound(fine) - sol.cFunc(fine)) <= 0.0]
    width = float(binding.max() - binding.min()) if binding.size else 0.0
    _claim(
        "tighter upper bound",
        "under a natural constraint the rule touches the bound only as "
        "m -> mNrmMin (the envelope has nothing to do)",
        f"binding set is [{binding.min():.6f}, {binding.max():.6f}], width "
        f"{width:.4e}, entirely below m0 = {m0:.4f}: "
        f"{bool(binding.size and binding.max() < m0)}",
        ok=bool(binding.size == 0 or (binding.max() < m0 and width < 0.01)),
    )
    _claim(
        "tighter upper bound",
        "the bound carries c(mNrmMin) = 0 for free",
        f"bound(mNrmMin) = {float(bound(np.array([sol.mNrmMin]))[0]):.3e}, "
        f"cMoM(mNrmMin) = {float(sol.cFunc(np.array([sol.mNrmMin]))[0]):.3e}",
        ok=abs(float(sol.cFunc(np.array([sol.mNrmMin]))[0])) < 1e-12,
    )
    _note(f"MPCmax = {sol.MPCmax:.6f} < 1, so the bound lies inside the budget line")


