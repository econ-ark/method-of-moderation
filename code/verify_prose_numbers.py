def check_moderation_ratio() -> None:
    """Bracket width, its share of the optimist's rule, and omega's landmarks."""
    logger.info("== Moderation ratio (fig:ModerationRatio paragraph) ==")
    agent = IndShockMoMConsumerType(**(PARAMS | SPARSE_GRID))
    agent.solve()
    sol = agent.solution[0]
    c_opt, c_pes, c_real = sol.Optimist.cFunc, sol.Pessimist.cFunc, sol.cFunc

    widths = np.array([float(c_opt(x) - c_pes(x)) for x in (0.5, 5.0, 20.0)])
    # hNrmEx is the gap between the two human wealths, hNrmOpt - hNrmPes, and
    # mNrmMin = -hNrmPes, so hNrmEx = hNrm + mNrmMin.
    analytic_width = sol.MPCmin * (sol.hNrm + sol.mNrmMin)
    _claim(
        "moderation ratio",
        "the bracket has constant width MPCmin * hNrmEx",
        f"cOpt-cPes at m = 0.5, 5, 20: {widths[0]:.8f}, {widths[1]:.8f}, "
        f"{widths[2]:.8f}; MPCmin*hNrmEx = {analytic_width:.8f}",
        ok=bool(np.ptp(widths) < 1e-10)
        and _close(float(widths[0]), float(analytic_width), 1e-8),
    )

    m_near = sol.mNrmMin + 1e-6
    share_near = float((c_opt(m_near) - c_pes(m_near)) / c_opt(m_near))
    share_10 = float((c_opt(10.0) - c_pes(10.0)) / c_opt(10.0))
    _claim(
        "moderation ratio",
        "in levels the bracket is more than half of the optimist's consumption "
        "near the constraint",
        f"(cOpt-cPes)/cOpt at m = mNrmMin+1e-6 is {share_near:.4f}",
        ok=share_near > 0.5,
    )
    _claim(
        "moderation ratio",
        "and under a tenth of it by m = 10",
        f"(cOpt-cPes)/cOpt at m = 10 is {share_10:.4f}",
        ok=share_10 < 0.1,
    )

    grid = np.linspace(sol.mNrmMin + 1e-9, 30.0, 600_001)
    omega = moderate(grid, c_opt, c_real(grid), c_pes)
    cross_half = float(grid[int(np.argmax(omega >= 0.5))])
    omega_15 = float(omega[int(np.argmin(np.abs(grid - 15.0)))])
    _claim(
        "moderation ratio",
        "omega climbs through 0.5 near m = 2.3",
        f"first crossing of 0.5 at m = {cross_half:.4f}",
        ok=_close(cross_half, 2.3, 0.05),
    )
    _claim(
        "moderation ratio",
        "and past 0.8 by m = 15",
        f"omega(15) = {omega_15:.4f}",
        ok=omega_15 > 0.8,
    )
    _claim(
        "moderation ratio",
        "omega climbs from zero at the constraint (omega in (0,1) strictly)",
        f"omega range over (mNrmMin, 30] = [{omega.min():.4f}, {omega.max():.4f}]",
        ok=bool(omega.min() > 0.0) and bool(omega.max() < 1.0),
    )
    cross_08 = float(grid[int(np.argmax(omega >= 0.8))])
    _note(f"omega first reaches 0.8 at m = {cross_08:.4f}")


